// Two matching strategies, chosen per the task's own safety rule ("prefix
// matching only where every row under that prefix is confirmed 410;
// exact-path matching otherwise"):
//
// 1. GONE_PREFIXES — six WordPress taxonomy archive types. Verified against
//    the spreadsheet: literally every row under each of these (142 rows
//    total: tag 37, category 35, profile 28, project 20, pj-categs 12,
//    pl-categs 10) is 410, with zero exceptions. No current Next.js route,
//    hospital slug, or migrated blog slug starts with any of these six
//    segment names (checked programmatically before writing this file), so
//    a whole-prefix rule is safe and also covers any sub-path WordPress
//    might have had under them that the sitemap crawl didn't catch.
//
// 2. GONE_EXACT_SLUGS — the remaining 37 "page"-group 410 rows (18
//    medical-park-* competitor hospital pages + 19 one-off retired pages:
//    old order/checkout flow, old doctor-profile index, old free-consult
//    page, etc.). These do NOT share one universally-safe prefix across
//    the whole set, so each is matched exactly rather than by a wildcard —
//    same rule as above, applied conservatively.
//
// 142 (prefixes) + 37 (exact) = 179, matching the spreadsheet's total.
//
// Separately, GTRANSLATE_PREFIXES (/tr, /fr, /de) is NOT from the
// spreadsheet — the sitemap crawl never saw these because the live
// WordPress .htaccess already blocks them (robots.txt also disallows
// them). This is a parallel, independently-approved rule (Phase 5A, §4),
// kept in its own list so it's never confused with an actual spreadsheet
// decision. `/es` is deliberately NOT included — see the Phase 5A report.
//
// PHASE_5E_ORGAN_TRANSPLANT_REMOVALS (3 rows) is a second, separate
// exception — also NOT from the spreadsheet. These 3 slugs were approved
// "MIGRATE / KEEP URL" in the migration map, but the site owner directed
// their removal (2026-10-10): MCT previously received an official warning
// over organ/kidney transplant content on the legacy site, and equivalent
// content must not exist on the new platform. Kept in its own list, same
// reason as GTRANSLATE_PREFIXES — never to be confused with an actual
// migration-map decision. See the Phase 5E report for the full rationale
// and the migration-map-conflict list. The matching import-script exclusion
// is scripts/import-blog-posts.mjs's EXCLUDED_SLUGS, so these can never be
// regenerated by a future re-import.

